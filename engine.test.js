const test = require('node:test');
const assert = require('node:assert/strict');
const { edit } = require('./engine.js');

test('змінює відмінювані форми зі словника', () => {
  assert.equal(
    edit('Іншого спеціального агента запросили до аудиторії.').text,
    'Иншого спеціяльного аґента запросили до авдиторії.'
  );
  assert.equal(
    edit('Про матеріали, марафоном і тріумфом.').text,
    'Про матеріяли, маратоном і тріюмфом.'
  );
});

test('родовий на -и не псує давальний', () => {
  assert.equal(edit('Без любові немає радості.').text, 'Без любови немає радости.');
  assert.equal(edit('Допомогли любові й раділи осені.').text, 'Допомогли любові й раділи осені.');
  assert.equal(edit('До смерті та без крові.').text, 'До смерти та без крови.');
  assert.equal(edit('Без можливості немає радості.').text, 'Без можливости немає радости.');
});

test('зберігає регістр, межі слів і вимикає окремі правила', () => {
  assert.equal(edit('ІНШОГО агента; суперагент.').text, 'ИНШОГО аґента; суперагент.');
  assert.equal(edit('іншого агента', { initial: false, loans: false }).text, 'іншого агента');
  assert.equal(edit('була у Европі', { euphony: false }).text, 'була у Европі');
});

test('милозвучність та повторне редагування', () => {
  const first = edit('мама і Олена була у Европі');
  assert.equal(first.text, 'мама й Олена була в Европі');
  assert.equal(edit(first.text).text, first.text);
});

test('нові редакційні основи охоплюють відмінки та похідні без загальної заміни літер', () => {
  assert.equal(edit('Інакше, іноді, інколи, інакшим способом.').text, 'Инакше, иноді, инколи, инакшим способом.');
  assert.equal(edit('Меморіалу й меморіальним ініціативам.').text, 'Меморіялу й меморіяльним ініціятивам.');
  assert.equal(edit('Без ініціативності, багатоголосності й одеськості.').text, 'Без ініціятивности, багатоголосности й одеськости.');
  assert.equal(edit('Медіа і медіапростору, медіакомпанії.').text, 'Медія й медіяпростору, медіякомпанії.');
  assert.equal(edit('Істина й інші слова.').text, 'Істина й инші слова.');
});

test('назви соцмереж виправляються за контекстом, телеграма як повідомлення зберігається', () => {
  assert.equal(edit('Інстаграм і інстаграмі.').text, 'Інстаґрам і інстаґрамі.');
  assert.equal(edit('Телеграм-канал і тг-канал.').text, 'Телеґрам-канал і тґ-канал.');
  assert.equal(edit('телеграм працює', { euphony: false }).text, 'телеґрам працює');
  assert.equal(edit('Instagram і Telegram-канал.').text, 'Інстаґрам і Телеґрам-канал.');
  assert.equal(edit('Пишіть у директі та месенджері телеграмі.').text, 'Пишіть у директі та месенджері телеґрамі.');
  assert.equal(edit('Надіслали телеграму поштою.').text, 'Надіслали телеграму поштою.');
  assert.equal(edit('Телеграма надійшла вранці.').text, 'Телеграма надійшла вранці.');
  assert.equal(edit('Багато телеграм надійшло вранці.').text, 'Багато телеграм надійшло вранці.');
});
