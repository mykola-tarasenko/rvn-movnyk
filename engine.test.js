const test = require('node:test');
const assert = require('node:assert/strict');
const { edit } = require('./engine.js');

test('змінює відмінювані форми зі словника', () => {
  assert.equal(
    edit('Іншого спеціального агента запросили до аудиторії.').text,
    'Иншого спеціяльного аґента запросили до авдиторії.'
  );
  assert.equal(
    edit('Про матеріали, марафоном і тріумфом.').text,
    'Про матеріяли, маратоном і тріюмфом.'
  );
});

test('родовий на -и не псує давальний', () => {
  assert.equal(edit('Без любові немає радості.').text, 'Без любови немає радости.');
  assert.equal(edit('Допомогли любові й раділи осені.').text, 'Допомогли любові й раділи осені.');
  assert.equal(edit('До смерті та без крові.').text, 'До смерти та без крови.');
  assert.equal(edit('Без можливості немає радості.').text, 'Без можливости немає радости.');
});

test('зберігає регістр, межі слів і вимикає окремі правила', () => {
  assert.equal(edit('ІНШОГО агента; суперагент; вагітна.').text, 'ИНШОГО аґента; супераґент; вагітна.');
  assert.equal(edit('іншого агента', { initial: false, loans: false }).text, 'іншого агента');
  assert.equal(edit('була у Европі', { euphony: false }).text, 'була у Европі');
});

test('милозвучність та повторне редагування', () => {
  const first = edit('мама і Олена була у Европі');
  assert.equal(first.text, 'мама й Олена була в Европі');
  assert.equal(edit(first.text).text, first.text);
});

test('нові редакційні основи охоплюють відмінки та похідні без загальної заміни літер', () => {
  assert.equal(edit('Інакше, іноді, інколи, інакшим способом.').text, 'Инакше, иноді, инколи, инакшим способом.');
  assert.equal(edit('Меморіалу й меморіальним ініціативам.').text, 'Меморіялу й меморіяльним ініціятивам.');
  assert.equal(edit('Без ініціативності, багатоголосності й одеськості.').text, 'Без ініціятивности, багатоголосности й одеськости.');
  assert.equal(edit('Медіа і медіапростору, медіакомпанії.').text, 'Медія й медіяпростору, медіякомпанії.');
  assert.equal(edit('Істина й інші слова.').text, 'Істина й инші слова.');
});

test('назви соцмереж виправляються за контекстом, телеграма як повідомлення зберігається', () => {
  assert.equal(edit('Інстаграм і інстаграмі.').text, 'Інстаґрам і інстаґрамі.');
  assert.equal(edit('Телеграм-канал і тг-канал.').text, 'Телеґрам-канал і тґ-канал.');
  assert.equal(edit('телеграм працює', { euphony: false }).text, 'телеґрам працює');
  assert.equal(edit('Instagram і Telegram-канал.').text, 'Інстаґрам і Телеґрам-канал.');
  assert.equal(edit('Пишіть у директі та месенджері телеграмі.').text, 'Пишіть у директі та месенджері телеґрамі.');
  assert.equal(edit('Надіслали телеграму поштою.').text, 'Надіслали телеграму поштою.');
  assert.equal(edit('Телеграма надійшла вранці.').text, 'Телеграма надійшла вранці.');
  assert.equal(edit('Багато телеграм надійшло вранці.').text, 'Багато телеграм надійшло вранці.');
});

test('милозвучність враховує вже виправлене попереднє слово', () => {
  assert.equal(edit('Він пішов в школу і в кімнату.').text, 'Він пішов у школу й у кімнату.');
  assert.equal(edit('Мама й в хаті, а мама і у Одесі.').text, 'Мама й у хаті, а мама і в Одесі.');
});

test('корінь РВН діє в похідних і складних словах, але не в омонімах', () => {
  assert.equal(
    edit('Планування, запланувати, генплан, міфічний, ефірний, агентство, європейці, матеріалізм, класний.').text,
    'Плянування, заплянувати, генплян, мітичний, етерний, аґентство, европейці, матеріялізм, клясний.'
  );
  const unchanged = 'Планета, планшет, трансплантація, вагітна, кефір, мігрень, колаборант, муміфікація, покласти, кластер, саудит, європакет.';
  assert.equal(edit(unchanged).text, unchanged);
  assert.equal(edit(unchanged).reviews.length, 0);
  const uncertain = edit('Планка');
  assert.equal(uncertain.text, 'Планка');
  assert.deepEqual(uncertain.reviews.map(item => item.replacements), [['Плянка']]);
});

test('клас і зал за РВН жіночого роду: неоднозначні форми лише пропонуються', () => {
  assert.equal(edit('До залу, у залу, у класі, з класом, класів.', { euphony: false }).text, 'До залі, у залю, у клясі, з клясою, кляс.');
  const review = edit('Великий зал. Зал був повний. Два класи.');
  assert.equal(review.text, 'Великий зал. Зал був повний. Два класи.');
  assert.deepEqual(review.reviews.map(item => [item.from, item.replacements]), [
    ['Великий зал', ['Велика заля', 'Велику залю']], ['Зал був повний', ['Заля була повна']], ['Два класи', ['Дві кляси']]
  ]);
});

test('клас і зал: злиті слова, числівник через прикметник, підмет і додаток', () => {
  assert.equal(edit('Учні спецкласу прийшли до кінозалу. Проводимо майстеркласи.', { euphony: false }).text, 'Учні спецкляси прийшли до кінозалі. Проводимо майстеркляси.');
  const untouched = 'Вона сказала, вони сказали. До вокзалу. Футзал і Ніклас.';
  assert.equal(edit(untouched).text, untouched);
  assert.equal(edit(untouched).reviews.length, 0);
  assert.equal(edit('Провели майстер-клас. Зал прикрасили квітами.').text, 'Провели майстер-клясу. Залю прикрасили квітами.');
  const review = edit('Два нові класи. Відбувся цікавий майстер-клас. Клас не був готовий. А зал швидко заповнився.');
  assert.deepEqual(review.reviews.map(item => item.replacements), [
    ['Дві нові кляси'], ['Відбулася цікава майстер-кляса'], ['Кляса не була готова'], ['заля швидко заповнилася']
  ]);
  for (const item of review.reviews) assert.equal(edit('Два нові класи. Відбувся цікавий майстер-клас. Клас не був готовий. А зал швидко заповнився.').text.slice(item.start, item.end), item.from);
});
